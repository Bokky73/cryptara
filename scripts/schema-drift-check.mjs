#!/usr/bin/env node
// Schema drift checker.
//
// Responsibilities:
//   (a) Read every `*.up.sql` file in `db/migrations/` in lexical order.
//   (b) Compute SHA-256 checksums and, when `DATABASE_URL` is set, compare them
//       against the `migration_history` table. Fail on mismatch or on unapplied
//       migrations.
//   (c) Regenerate the expected schema by concatenating the canonical migration
//       chain and diff it against `frontend/src/server/storage/schema.sql`
//       (normalized whitespace/comments). Exit non-zero with a clear diff when
//       they diverge.
//
// Flags:
//   --write   Rewrite `schema.sql` from the canonical chain (used so CI can
//             verify `--check` mode).
//   --check   Explicit check mode (default). Fails on drift.
//
// Usage:
//   node scripts/schema-drift-check.mjs
//   node scripts/schema-drift-check.mjs --write
//   node scripts/schema-drift-check.mjs --check

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const MIGRATIONS_DIR = path.join(ROOT, 'db', 'migrations');
const SCHEMA_FILE = path.join(
  ROOT,
  'frontend',
  'src',
  'server',
  'storage',
  'schema.sql',
);

const MIGRATION_HISTORY_TABLE = 'migration_history';

const args = new Set(process.argv.slice(2));
const WRITE_MODE = args.has('--write');
const CHECK_MODE = args.has('--check') || !WRITE_MODE;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function sha256(content) {
  return createHash('sha256').update(content, 'utf8').digest('hex');
}

/**
 * Normalize SQL for comparison purposes:
 *   - strip line comments (`-- ...`) and block comments (`/* ... *\/`)
 *   - collapse all whitespace runs to a single space
 *   - trim
 *   - drop trailing semicolons / empty statements
 */
function normalizeSql(sql) {
  let out = sql;

  // Strip block comments (non-greedy, across newlines).
  out = out.replace(/\/\*[\s\S]*?\*\//g, ' ');

  // Strip line comments.
  out = out.replace(/--[^\n\r]*/g, ' ');

  // Collapse whitespace.
  out = out.replace(/\s+/g, ' ').trim();

  // Normalize statement separators: remove empty statements.
  out = out
    .split(';')
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .join(';\n');

  return out;
}

/**
 * Produce a line-by-line diff between two normalized strings.
 * Returns an array of human-readable diff lines.
 */
function diffLines(expected, actual) {
  const a = expected.split('\n');
  const b = actual.split('\n');
  const lines = [];

  const max = Math.max(a.length, b.length);
  for (let i = 0; i < max; i += 1) {
    const left = a[i];
    const right = b[i];
    if (left === right) {
      continue;
    }
    if (left !== undefined) {
      lines.push(`- ${left}`);
    }
    if (right !== undefined) {
      lines.push(`+ ${right}`);
    }
  }

  return lines;
}

async function listUpMigrations() {
  if (!existsSync(MIGRATIONS_DIR)) {
    throw new Error(`Migrations directory not found: ${MIGRATIONS_DIR}`);
  }

  const entries = await readdir(MIGRATIONS_DIR);
  const upFiles = entries
    .filter((name) => name.endsWith('.up.sql'))
    .sort((x, y) => (x < y ? -1 : x > y ? 1 : 0));

  if (upFiles.length === 0) {
    throw new Error(`No *.up.sql migrations found in ${MIGRATIONS_DIR}`);
  }

  const migrations = [];
  for (const name of upFiles) {
    const fullPath = path.join(MIGRATIONS_DIR, name);
    const content = await readFile(fullPath, 'utf8');
    migrations.push({
      name,
      // Migration id is the filename without the `.up.sql` suffix.
      id: name.replace(/\.up\.sql$/, ''),
      content,
      checksum: sha256(content),
    });
  }

  return migrations;
}

/**
 * Build the canonical schema by concatenating the migration chain.
 * Each migration is wrapped in a marker comment so the generated file is
 * self-documenting and stable.
 */
function buildCanonicalSchema(migrations) {
  const header = [
    '-- AUTO-GENERATED FILE. DO NOT EDIT BY HAND.',
    '-- Generated by scripts/schema-drift-check.mjs from db/migrations/*.up.sql.',
    '-- Regenerate with: node scripts/schema-drift-check.mjs --write',
    '',
  ].join('\n');

  const body = migrations
    .map((m) => {
      const trimmed = m.content.replace(/\s+$/, '');
      return [
        `-- >>> migration: ${m.name} (sha256:${m.checksum})`,
        trimmed,
        `-- <<< migration: ${m.name}`,
        '',
      ].join('\n');
    })
    .join('\n');

  return `${header}\n${body}`.replace(/\s+$/, '') + '\n';
}

// ---------------------------------------------------------------------------
// Database verification (optional; only when DATABASE_URL is set)
// ---------------------------------------------------------------------------

async function verifyAgainstDatabase(migrations) {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    console.log(
      'schema-drift-check: DATABASE_URL not set; skipping migration_history verification.',
    );
    return;
  }

  let pg;
  try {
    pg = await import('pg');
  } catch (err) {
    throw new Error(
      'DATABASE_URL is set but the "pg" package is not installed. ' +
        'Install it (npm i pg) or unset DATABASE_URL. Original error: ' +
        (err && err.message ? err.message : String(err)),
    );
  }

  const { Client } = pg.default ?? pg;
  const client = new Client({ connectionString: databaseUrl });

  await client.connect();
  try {
    // Ensure the history table exists so we can distinguish "no migrations
    // applied" from "table missing".
    const tableCheck = await client.query(
      `SELECT to_regclass($1) AS reg`,
      [MIGRATION_HISTORY_TABLE],
    );
    const tableExists = tableCheck.rows[0]?.reg != null;

    if (!tableExists) {
      throw new Error(
        `Table "${MIGRATION_HISTORY_TABLE}" does not exist. ` +
          'Run `node scripts/migrate.mjs` to apply migrations first.',
      );
    }

    const { rows } = await client.query(
      `SELECT id, checksum FROM ${MIGRATION_HISTORY_TABLE} ORDER BY id ASC`,
    );

    const applied = new Map(rows.map((r) => [String(r.id), String(r.checksum)]));
    const expected = new Map(migrations.map((m) => [m.id, m.checksum]));

    const problems = [];

    // Unapplied migrations.
    for (const m of migrations) {
      if (!applied.has(m.id)) {
        problems.push(`unapplied migration: ${m.name} (${m.id})`);
      }
    }

    // Checksum mismatches.
    for (const m of migrations) {
      const appliedChecksum = applied.get(m.id);
      if (appliedChecksum !== undefined && appliedChecksum !== m.checksum) {
        problems.push(
          `checksum mismatch for ${m.name} (${m.id}): ` +
            `applied=${appliedChecksum} expected=${m.checksum}`,
        );
      }
    }

    // Applied migrations that no longer exist on disk.
    for (const id of applied.keys()) {
      if (!expected.has(id)) {
        problems.push(`applied migration missing from disk: ${id}`);
      }
    }

    if (problems.length > 0) {
      throw new Error(
        `Migration history verification failed:\n  - ${problems.join('\n  - ')}`,
      );
    }

    console.log(
      `schema-drift-check: migration_history verified (${migrations.length} migrations).`,
    );
  } finally {
    await client.end();
  }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const migrations = await listUpMigrations();

  console.log(
    `schema-drift-check: found ${migrations.length} migration(s) in db/migrations.`,
  );
  for (const m of migrations) {
    console.log(`  ${m.name}  sha256:${m.checksum}`);
  }

  // (b) Verify against the database when configured.
  await verifyAgainstDatabase(migrations);

  // (c) Regenerate expected schema and compare against schema.sql.
  const expectedSchema = buildCanonicalSchema(migrations);

  if (WRITE_MODE) {
    await writeFile(SCHEMA_FILE, expectedSchema, 'utf8');
    console.log(`schema-drift-check: wrote ${path.relative(ROOT, SCHEMA_FILE)}.`);
    return;
  }

  if (!CHECK_MODE) {
    return;
  }

  if (!existsSync(SCHEMA_FILE)) {
    throw new Error(
      `schema.sql not found at ${path.relative(ROOT, SCHEMA_FILE)}. ` +
        'Run `node scripts/schema-drift-check.mjs --write` to generate it.',
    );
  }

  const actualSchema = await readFile(SCHEMA_FILE, 'utf8');

  const normalizedExpected = normalizeSql(expectedSchema);
  const normalizedActual = normalizeSql(actualSchema);

  if (normalizedExpected !== normalizedActual) {
    const diff = diffLines(normalizedExpected, normalizedActual);
    const preview = diff.slice(0, 200).join('\n');
    const truncated = diff.length > 200 ? `\n... (${diff.length - 200} more lines)` : '';

    throw new Error(
      `Schema drift detected: ${path.relative(ROOT, SCHEMA_FILE)} diverges from ` +
        `db/migrations/*.up.sql.\n` +
        `Regenerate with: node scripts/schema-drift-check.mjs --write\n\n` +
        `--- expected (from migrations)\n+++ actual (schema.sql)\n` +
        `${preview}${truncated}`,
    );
  }

  console.log('schema-drift-check: OK (schema.sql matches canonical migrations).');
}

main().catch((err) => {
  console.error(`schema-drift-check: FAILED\n${err && err.message ? err.message : err}`);
  process.exit(1);
});