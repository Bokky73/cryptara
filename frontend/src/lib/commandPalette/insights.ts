export function insightSlugFromPath(pathname: string | null): string | null {
  const slug = pathname?.match(/^\/insights\/([a-z0-9-]+)\/?$/)?.[1];
  return slug && INSIGHTS.some(([known]) => known === slug) ? slug : null;
}
