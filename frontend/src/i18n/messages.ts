export type MessageKey = (typeof translations)[number][0];
export type Translate = (key: MessageKey, variables?: Record<string, string | number>) => string;

const english = Object.fromEntries(translations.map(([key, value]) => [key, value])) as Record<MessageKey, string>;
const turkish = Object.fromEntries(translations.map(([key, , value]) => [key, value])) as Record<MessageKey, string>;

export const messageCatalogs: Record<Locale, Record<MessageKey, string>> = {
  en: english,
  tr: turkish,
};

function interpolate(template: string, variables?: Record<string, string | number>): string {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => Object.hasOwn(variables, key) ? String(variables[key]) : match);
}

export function messages(locale: Locale): Translate {
  const catalog = messageCatalogs[locale] ?? messageCatalogs.en;
  return (key, variables) => {
    if (!Object.hasOwn(catalog, key)) throw new Error("Unknown translation key");
    return interpolate(catalog[key], variables);
  };
}
